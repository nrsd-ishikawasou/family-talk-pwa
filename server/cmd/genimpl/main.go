// Command genimpl は、oapi-codegen が生成した StrictServerInterface を openapi のタグごとの interface に分け、
// srv-boundary の Implementations を書く（基本設計書 第14章 8、全体実装設計書 5.1）。
// 各ブロックは自分のタグの interface を実装し、実装の抜けはコンパイルの時に分かる。
//
// あわせて、束ねた spec を go:embed で取り込む spec.gen.go を out と同じ置き場に書く（要求の検証が読む）。
//
// 使い方：go run ./cmd/genimpl -gen <boundary.gen.go> -spec <openapi.bundled.yaml> -out <implementations.gen.go>
// spec は out と同じ置き場に置く（go:embed は package の置き場の中しか読めない）。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// method は StrictServerInterface の 1 つの操作。
type method struct {
	name string
	sig  string
	doc  string
}

func main() {
	genPath := flag.String("gen", "", "oapi-codegen の生成ファイル")
	specPath := flag.String("spec", "", "束ねた openapi")
	outPath := flag.String("out", "", "書き出す先")
	flag.Parse()
	if err := run(*genPath, *specPath, *outPath); err != nil {
		fmt.Fprintln(os.Stderr, "genimpl:", err)
		os.Exit(1)
	}
}

func run(genPath, specPath, outPath string) error {
	methods, err := strictMethods(genPath)
	if err != nil {
		return err
	}
	tags, err := operationTags(specPath)
	if err != nil {
		return err
	}
	byTag := map[string][]method{}
	for _, m := range methods {
		tag, ok := tags[strings.ToLower(m.name)]
		if !ok {
			return fmt.Errorf("操作 %s のタグが openapi に無い", m.name)
		}
		byTag[tag] = append(byTag[tag], m)
	}
	src, err := render(byTag)
	if err != nil {
		return err
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		return err
	}
	return writeSpecEmbed(specPath, outPath)
}

// writeSpecEmbed は束ねた spec を取り込む spec.gen.go を書く。
func writeSpecEmbed(specPath, outPath string) error {
	dir := filepath.Dir(outPath)
	specAbs, err := filepath.Abs(specPath)
	if err != nil {
		return err
	}
	dirAbs, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	if filepath.Dir(specAbs) != dirAbs {
		return fmt.Errorf("spec は out と同じ置き場に置く: %s", specPath)
	}
	var b bytes.Buffer
	writeHeader(&b)
	b.WriteString("package gen\n\nimport _ \"embed\"\n\n")
	b.WriteString("// Spec は束ねた openapi（YAML）。要求の検証が読む。\n")
	fmt.Fprintf(&b, "//\n//go:embed %s\nvar Spec []byte\n", filepath.Base(specAbs))
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "spec.gen.go"), src, 0o644)
}

// writeHeader は生成ファイルの頭の注記を書く。
func writeHeader(b *bytes.Buffer) {
	b.WriteString("// Code generated by genimpl from api/openapi.yaml. DO NOT EDIT.\n\n")
	// REUSE-IgnoreStart
	b.WriteString("// SPDX-FileCopyrightText: 2026 株式会社流山ソフトウェア開発 (Nagareyama Software Development Co., Ltd.)\n")
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	// REUSE-IgnoreEnd
}

// strictMethods は生成ファイルの StrictServerInterface の操作を、書かれた順に返す。
func strictMethods(path string) ([]method, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var out []method
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			it, ok := ts.Type.(*ast.InterfaceType)
			if ts.Name.Name != "StrictServerInterface" || !ok {
				continue
			}
			for _, fld := range it.Methods.List {
				ft, ok := fld.Type.(*ast.FuncType)
				if !ok || len(fld.Names) != 1 {
					continue
				}
				var buf bytes.Buffer
				if err := printer.Fprint(&buf, fset, ft); err != nil {
					return nil, err
				}
				doc := ""
				if fld.Doc != nil {
					doc = strings.TrimSpace(fld.Doc.Text())
				}
				out = append(out, method{name: fld.Names[0].Name, sig: strings.TrimPrefix(buf.String(), "func"), doc: doc})
			}
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("StrictServerInterface が無い: %s", path)
	}
	return out, nil
}

// operationTags は operationId（小文字）からタグへの表。タグは 1 つの操作に 1 つ。
func operationTags(path string) (map[string]string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	type operation struct {
		OperationId string   `yaml:"operationId"`
		Tags        []string `yaml:"tags"`
	}
	var spec struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(b, &spec); err != nil {
		return nil, err
	}
	methods := map[string]bool{"get": true, "put": true, "post": true, "delete": true, "options": true, "head": true, "patch": true, "trace": true}
	out := map[string]string{}
	for _, item := range spec.Paths {
		for key, node := range item {
			if !methods[key] {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return nil, err
			}
			if op.OperationId == "" {
				continue
			}
			if len(op.Tags) != 1 {
				return nil, fmt.Errorf("操作 %s のタグが 1 つでない", op.OperationId)
			}
			out[strings.ToLower(op.OperationId)] = op.Tags[0]
		}
	}
	return out, nil
}

// exported はタグの名を Go の名にする（setup を Setup）。
func exported(tag string) string {
	return strings.ToUpper(tag[:1]) + tag[1:]
}

// callArgs は署名の引数の名を並べる（ctx, request）。
func callArgs(sig string) string {
	open := strings.Index(sig, "(")
	close := strings.Index(sig, ")")
	var names []string
	for _, p := range strings.Split(sig[open+1:close], ",") {
		fields := strings.Fields(strings.TrimSpace(p))
		if len(fields) > 0 {
			names = append(names, fields[0])
		}
	}
	return strings.Join(names, ", ")
}

// render は生成ファイルの本文を作る。
func render(byTag map[string][]method) ([]byte, error) {
	tags := make([]string, 0, len(byTag))
	for t := range byTag {
		tags = append(tags, t)
	}
	sort.Strings(tags)
	var b bytes.Buffer
	writeHeader(&b)
	b.WriteString("package gen\n\nimport \"context\"\n\n")
	for _, t := range tags {
		fmt.Fprintf(&b, "// %sApi は openapi のタグ %s の操作。\ntype %sApi interface {\n", exported(t), t, exported(t))
		for _, m := range byTag[t] {
			if m.doc != "" {
				for _, line := range strings.Split(m.doc, "\n") {
					fmt.Fprintf(&b, "\t// %s\n", line)
				}
			}
			fmt.Fprintf(&b, "\t%s%s\n", m.name, m.sig)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// Implementations はタグごとの実装を束ねる（srv-boundary の Implementations）。\ntype Implementations struct {\n")
	for _, t := range tags {
		fmt.Fprintf(&b, "\t%s %sApi\n", exported(t), exported(t))
	}
	b.WriteString("}\n\n")
	b.WriteString("var _ StrictServerInterface = Implementations{}\n\n")
	for _, t := range tags {
		for _, m := range byTag[t] {
			fmt.Fprintf(&b, "// %s はタグ %s の実装へ渡す。\nfunc (i Implementations) %s%s {\n\treturn i.%s.%s(%s)\n}\n\n",
				m.name, t, m.name, m.sig, exported(t), m.name, callArgs(m.sig))
		}
	}
	return format.Source(b.Bytes())
}
