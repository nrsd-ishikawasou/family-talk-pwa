"""api/ の errors.yaml、ratelimits.yaml、config.yaml から Go の定数を作る（全体実装設計書 5.1、srv-common.md）。

使い方：python -m tools.gen_errors [--out <dir>]
  --out：書き出す先（既定は server/internal/common/gen）。生成の再現性は 2 つの先に書いて比べる（基本設計書 第14章 8）。
生成ファイルはコミットしない（.gitignore）。
"""
import argparse
import json
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
API = ROOT / 'api'
OUT = ROOT / 'server' / 'internal' / 'common' / 'gen'
# 生成ファイルの頭（SPDX の行を含む。生成ファイルにも著作権とライセンスを表示する）。
# REUSE-IgnoreStart
HEAD = ('// Code generated by tools/gen_errors from api/{src}. DO NOT EDIT.\n\n'
        '// SPDX-FileCopyrightText: 2026 株式会社流山ソフトウェア開発 (Nagareyama Software Development Co., Ltd.)\n'
        '// SPDX-License-Identifier: Apache-2.0\n\npackage gen\n\n')
# REUSE-IgnoreEnd


def q(s):
    """Go の文字列の書き方（JSON の文字列は Go の解釈できる文字列の書き方と同じ）。"""
    return json.dumps(s, ensure_ascii=False)


def ident(code):
    """AUTH-001 を AUTH001 に。"""
    return re.sub(r'[^A-Za-z0-9]', '', code)


def camel(key):
    """server.https_port を ServerHttpsPort に。"""
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[._]', key) if p)


def errors_go(doc):
    out = [HEAD.format(src='errors.yaml')]
    out.append('// Retry は再試行の可否。by_state は状態で決まる。NotApplicable は警告の行（エラーコード表の欄）。\n')
    out.append('type Retry int\n\nconst (\n\tRetryNo Retry = iota\n\tRetryYes\n\tRetryByState\n\tRetryNotApplicable\n)\n\n')
    out.append('// ErrorDef はエラーコード表の 1 行（基本設計書 第2章 9.2）。\n')
    out.append('// Status が 0 の行は HTTP の応答に現れない（SHELL：Android のシェルの中）。\n')
    out.append('type ErrorDef struct {\n\tCode        string\n\tStatus      int\n\tTitle       string\n\tRetry       Retry\n'
               '\tParamsJSON  string\n\tLog         bool\n\tGlobal      bool\n\tWarning     bool\n\tUserTextKey string\n\tTest        string\n}\n\n')
    out.append('// 番号の定数。\nconst (\n')
    for r in doc['rows']:
        out.append(f'\t{ident(r["code"])} = {q(r["code"])}\n')
    out.append(')\n\n')
    out.append('// Errors はエラーコード表の全行。\nvar Errors = map[string]ErrorDef{\n')
    for r in doc['rows']:
        retry = {True: 'RetryYes', False: 'RetryNo', 'by_state': 'RetryByState', None: 'RetryNotApplicable'}[r.get('retryable')]
        out.append(f'\t{ident(r["code"])}: {{Code: {ident(r["code"])}, Status: {int(r.get("status") or 0)}, Title: {q(r["title"])}, '
                   f'Retry: {retry}, ParamsJSON: {q(json.dumps(r["params"], ensure_ascii=False, sort_keys=True))}, '
                   f'Log: {"true" if r["log"] else "false"}, Global: {"true" if r["scope"] == "global" else "false"}, '
                   f'Warning: {"true" if r.get("warning") else "false"}, '
                   f'UserTextKey: {q(r["user_text_key"])}, Test: {q(r["test"])}}},\n')
    out.append('}\n\n')
    out.append('// Retired は消した番号（再利用しない）。\nvar Retired = []string{')
    out.append(', '.join(q(c) for c in doc.get('retired') or []))
    out.append('}\n')
    return ''.join(out)


def ratelimits_go(doc):
    out = [HEAD.format(src='ratelimits.yaml')]
    out.append('// Limit は 1 つの上限（key ごとの token bucket。window は秒）。\n')
    out.append('type Limit struct {\n\tKey    string\n\tLimit  int\n\tWindow int\n\tBurst  int\n}\n\n')
    out.append('// Policy はレート制限の 1 行（基本設計書 第2章 9.3）。\n')
    out.append('type Policy struct {\n\tName     string\n\tOnExceed string\n\tLimits   []Limit\n}\n\n')
    out.append('// Policies は初期値の全行。\nvar Policies = []Policy{\n')
    for p in doc['policies']:
        lim = ', '.join(f'{{Key: {q(x["key"])}, Limit: {int(x["limit"])}, Window: {int(x["window"])}, Burst: {int(x["burst"])}}}'
                        for x in p['limits'])
        out.append(f'\t{{Name: {q(p["name"])}, OnExceed: {q(p["on_exceed"])}, Limits: []Limit{{{lim}}}}},\n')
    out.append('}\n')
    return ''.join(out)


def required(it):
    """既定値が無く環境変数で与える項目（server.domain、server.dns_provider）。"""
    return it['default'] is None and 'env' in (it.get('layers') or [])


def config_go(doc):
    out = [HEAD.format(src='config.yaml')]
    out.append('// Item は設定の 1 項目（基本設計書 第11章 7.2）。DefaultJSON は既定値の JSON（null は値なし）。\n')
    out.append('// Required は既定値が無く環境変数で与える項目（無ければ起動しない）。Nullable は null を値として許す項目（NullMeans はその意味）。\n')
    out.append('type Item struct {\n\tKey         string\n\tType        string\n\tDefaultJSON string\n\tLayers      []string\n'
               '\tEnv         string\n\tMin         *int64\n\tMax         *int64\n\tEnum        []string\n\tLocked      bool\n'
               '\tRequired    bool\n\tNullable    bool\n\tNullMeans   string\n}\n\n')
    out.append('func i64(v int64) *int64 { return &v }\n\n')
    out.append('// 鍵の定数。\nconst (\n')
    for it in doc['items']:
        out.append(f'\tKey{camel(it["key"])} = {q(it["key"])}\n')
    out.append(')\n\n')
    out.append('// Items は設定の全項目。\nvar Items = []Item{\n')
    for it in doc['items']:
        rng = it.get('range') or {}
        mn = f'i64({int(rng["min"])})' if 'min' in rng else 'nil'
        mx = f'i64({int(rng["max"])})' if 'max' in rng else 'nil'
        enum = '[]string{' + ', '.join(q(str(e)) for e in rng['enum']) + '}' if 'enum' in rng else 'nil'
        layers = '[]string{' + ', '.join(q(x) for x in it.get('layers') or []) + '}'
        out.append(f'\t{{Key: Key{camel(it["key"])}, Type: {q(it["type"])}, '
                   f'DefaultJSON: {q(json.dumps(it["default"], ensure_ascii=False, sort_keys=True))}, Layers: {layers}, '
                   f'Env: {q(it.get("env") or "")}, Min: {mn}, Max: {mx}, Enum: {enum}, '
                   f'Locked: {"true" if it.get("locked_when_env_or_file") else "false"}, '
                   f'Required: {"true" if required(it) else "false"}, '
                   f'Nullable: {"true" if "null_means" in rng else "false"}, NullMeans: {q(rng.get("null_means") or "")}}},\n')
    out.append('}\n')
    return ''.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', default=str(OUT))
    a = ap.parse_args()
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    load = lambda n: yaml.safe_load((API / n).read_text(encoding='utf-8'))
    (out / 'errors.go').write_text(errors_go(load('errors.yaml')), encoding='utf-8')
    (out / 'ratelimits.go').write_text(ratelimits_go(load('ratelimits.yaml')), encoding='utf-8')
    (out / 'config.go').write_text(config_go(load('config.yaml')), encoding='utf-8')
    print(f'書いた：{out}（errors.go、ratelimits.go、config.go）')


if __name__ == '__main__':
    main()
